"""
 默认参数也称为缺省参数,用于在定义函数时,为参数提供默认值,调用函数时,可以不传递有默认值的参数。

 注意:默认参数必须放在没有默认值的参数列表的后面,一个函数在定义时是可以设置多个默认参数的。
 注意:函数调用时,如果为默认参数传递了值,则会修改默认的参数值;如果没有传递该参数,则直接使用默认值。
"""

def reg_stu(name,age,gender,city="北京") :   # 默认参数，city="北京"--> 默认参数必须放在没有默认值的参数列表的后面
    print("姓名:",name,"年龄",age,"性别",gender,"城市",city)
    return {"姓名:":name,"年龄":age,"性别":gender,"城市":city}

stu = reg_stu("张三",18,"男")   # 未指定参数city，默认为 北京
print(stu)

stu2 = reg_stu("李四",20,"男","深圳")   # 指定参数city为 深圳
print(stu2)